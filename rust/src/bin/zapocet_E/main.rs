/*
Zápočet — E
Název: Druhé největší číslo v poli

Тест на оценку 3: найти второе максимальное число в массиве.
Это учебное решение по описанию теста, а не копия полного условия.
Здесь второй максимум — второй элемент по убыванию с учётом повторов:
для [9, 9, 5] ответ 9. Если нужны разные значения, правило будет другим.
*/

// &[i32] — ссылка на последовательность целых чисел: функция не копирует и не меняет массив.
// Option<i32> позволяет вернуть Some(ответ) или None, если элементов недостаточно.
fn second_maximum(numbers: &[i32]) -> Option<i32> {
    if numbers.len() < 2 {
        return None;
    }

    // Располагаем первые два элемента по убыванию в двух переменных.
    // Не начинаем с 0: в массиве могут быть только отрицательные числа.
    // Инициализация реальными элементами работает даже для значения i32::MIN.
    let mut maximum = numbers[0];
    let mut second = numbers[1];
    if second > maximum {
        let temp = maximum;
        maximum = second;
        second = temp;
    }

    // Первые два элемента уже учтены. Индексы начинаются с 0, поэтому следующий — 2.
    let mut index: usize = 2;
    while index < numbers.len() {
        let current = numbers[index];

        if current > maximum {
            // Новый лидер вытесняет старого на второе место.
            // Сначала сохраняем старый maximum, иначе потеряем его значение.
            second = maximum;
            maximum = current;
        } else if current > second {
            // Лидер остался прежним, но второе место можно улучшить.
            // Равный maximum элемент тоже может попасть сюда: повторы учитываются.
            second = current;
        }

        // После каждого шага maximum и second — два наибольших элемента
        // уже просмотренной части массива. Остальные элементы хранить не нужно.
        index += 1;
    }

    // Один проход: время O(n), дополнительная память O(1), сортировка не нужна.
    Some(second)
}

fn main() {
    // Для тренировки меняйте массив: порядок чисел не влияет на ответ.
    let numbers = [2, 5, 7, 1, 4, 6, 9, 8, 2];
    println!("Массив: {numbers:?}");

    match second_maximum(&numbers) {
        Some(value) => println!("Второе максимальное число: {value}"),
        None => println!("Для второго максимума нужны хотя бы два элемента."),
    }
}
